#!/usr/bin/env node
// Use the installed Keystone initializer rather than a second, drifting copy of it.
// Ordering/omission rules mirror Core 6.5.3 create-admin-meta; verified by adminMeta QA.
import { getContext } from '@keystone-6/core/context';
import * as PrismaModule from '@prisma/client';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import config from '../index';

const context = getContext(config, PrismaModule);
const lists = context.__internal.lists;
const omitted = new Set(Object.entries(lists).filter(([, list]) => !list.graphql.isEnabled.query).map(([key]) => key));
const views: string[] = [];
for (const [key, list] of Object.entries(lists)) {
  if (omitted.has(key)) continue;
  for (const field of Object.values(list.fields)) {
    if (field.dbField.kind === 'relation' && omitted.has(field.dbField.list)) continue;
    if (Object.values(field.graphql.isEnabled).every(value => value === false)) continue;
    for (const view of [field.views, field.ui.views]) {
      if (view && !views.includes(view)) views.push(view);
    }
  }
}
const names = views.map(view => {
  if (view.endsWith('/admin-ui/id-field-view')) return 'id';
  if (view === '@keystone-6/fields-document/views') return 'document';
  const match = view.match(/^@keystone-6\/core\/fields\/types\/([^/]+)\/views$/);
  if (!match) throw new Error(`Unmapped Keystone field view: ${view}`);
  return match[1];
});
if (names.shift() !== 'id') throw new Error('Expected Keystone id field at viewsIndex zero');
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), 'index.ts'),
  `// Generated by generate-view-order.ts from installed Keystone metadata.\nexport const VIEW_ORDER = ${JSON.stringify(names, null, 2)};\n`);
console.log(`Generated ${names.length} field views`);
